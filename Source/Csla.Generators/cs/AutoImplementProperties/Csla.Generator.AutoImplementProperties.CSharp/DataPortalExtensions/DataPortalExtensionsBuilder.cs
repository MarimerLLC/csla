using System.CodeDom.Compiler;
using Csla.Generator.AutoImplementProperties.CSharp.DataPortalOperations;
using Csla.Generator.AutoImplementProperties.CSharp.DataPortalOperations.Models;
using Microsoft.CodeAnalysis.CSharp;

namespace Csla.Generator.AutoImplementProperties.CSharp.DataPortalExtensions
{
  /// <summary>
  /// Builds the static class containing the strongly typed data portal
  /// extension methods for a business type.
  /// </summary>
  internal static class DataPortalExtensionsBuilder
  {
    private const string ReceiverName = "portal";
    private const string InvokerName = "__invoker";

    /// <summary>
    /// Build the generated source for a business type.
    /// Returns null when nothing is generated.
    /// </summary>
    public static string? Build(ExtensionGenerationModel model)
    {
      var type = model.Type;
      var (methods, _) = Analyze(model);
      if (methods.Count == 0)
        return null;

      using var stringWriter = new StringWriter();
      var writer = new IndentedTextWriter(stringWriter, "  ");

      writer.WriteLine("//<auto-generated/>");
      writer.WriteLine("#nullable enable");
      writer.WriteLineNoTabs(string.Empty);

      if (type.Namespace.Length > 0)
      {
        writer.WriteLine($"namespace {type.Namespace}");
        OpenBlock(writer);
      }

      // Different business types can map to the same class name (for example
      // a top-level Outer_Inner and a nested Outer.Inner). The partial parts
      // then merge; only a public business type states the accessibility so
      // the parts never conflict, and the methods carry their own accessibility.
      var classModifiers = type.Visibility == TypeVisibility.Public ? "public static partial" : "static partial";
      writer.WriteLine("/// <summary>");
      writer.WriteLine($"/// Strongly typed data portal extension methods for <see cref=\"{type.FullyQualifiedName}\"/>.");
      writer.WriteLine("/// </summary>");
      writer.WriteLine($"{classModifiers} class {type.ExtensionClassName}");
      OpenBlock(writer);

      var isFirst = true;
      foreach (var method in methods)
      {
        if (!isFirst)
          writer.WriteLineNoTabs(string.Empty);
        isFirst = false;
        AppendMethod(writer, type, method);
      }

      CloseBlock(writer);

      if (type.Namespace.Length > 0)
        CloseBlock(writer);

      return stringWriter.ToString();
    }

    /// <summary>
    /// Selects the extension methods generated for a business type, and
    /// explains, as diagnostics, why any are not generated. The generator
    /// uses the methods and the analyzer reports the diagnostics, so both
    /// apply the same rules.
    /// </summary>
    public static (List<ExtensionMethod> Methods, List<DiagnosticInfo> Diagnostics) Analyze(ExtensionGenerationModel model)
    {
      var type = model.Type;
      var diagnostics = new List<DiagnosticInfo>();
      var none = new List<ExtensionMethod>();

      if (type.IsGeneric)
      {
        diagnostics.Add(Diagnostic(DataPortalOperationsDiagnostics.GenericExtensionsNotGeneratedId, type.Location, type.TypeName));
        return (none, diagnostics);
      }

      var invalidReason = type switch
      {
        { IsCslaObject: false } => "the type does not implement Csla.Core.ICslaObject",
        { IsAbstract: true } => "the type is abstract",
        { Visibility: TypeVisibility.Private } => "the type is not accessible outside its containing type",
        _ => null
      };
      if (invalidReason is not null)
      {
        diagnostics.Add(Diagnostic(DataPortalOperationsDiagnostics.InvalidExtensionsTargetId, type.Location, type.TypeName, invalidReason));
        return (none, diagnostics);
      }

      if (type.Prefix.Length > 0 && !SyntaxFacts.IsValidIdentifier(type.Prefix))
      {
        diagnostics.Add(Diagnostic(DataPortalOperationsDiagnostics.InvalidExtensionPrefixId, type.Location, type.TypeName, type.Prefix));
        return (none, diagnostics);
      }

      return (SelectMethods(model, diagnostics), diagnostics);
    }

    private static List<ExtensionMethod> SelectMethods(ExtensionGenerationModel model, List<DiagnosticInfo> diagnostics)
    {
      var type = model.Type;
      var result = new List<ExtensionMethod>();
      var signatures = new HashSet<string>(StringComparer.Ordinal);
      var (_, collisions) = DataPortalOperationsBuilder.SelectNamedDispatchMethods(model.Methods);

      foreach (var method in model.Methods)
      {
        if (method.NoExtension || !method.CanDispatch)
          continue;

        // Methods sharing an operation name differ only in injected parameters,
        // so they would produce identical extension methods; the runtime's
        // choice is reported by the operations analyzer.
        if (collisions.Any(c => ReferenceEquals(c.Loser, method)))
          continue;

        var criteria = method.CriteriaParameters.ToList();
        var inaccessible = criteria.FirstOrDefault(p => p.Visibility == TypeVisibility.Private);
        if (inaccessible is not null)
        {
          diagnostics.Add(Diagnostic(DataPortalOperationsDiagnostics.InaccessibleParameterTypeId, method.Location, method.MethodDisplay, inaccessible.Name.TrimStart('@'), inaccessible.PatternTypeDisplay));
          continue;
        }

        var baseName = method.MethodName.TrimStart('@');
        if (baseName.EndsWith("Async", StringComparison.Ordinal) && baseName.Length > "Async".Length)
          baseName = baseName.Substring(0, baseName.Length - "Async".Length);

        var isChild = method.Kind is "CreateChild" or "FetchChild";
        var receiverInterface = isChild ? "IChildDataPortal" : "IDataPortal";
        var hiddenNames = isChild ? type.ChildHiddenNames : type.RootHiddenNames;
        var parameterTypes = string.Join(",", criteria.Select(p => p.PatternTypeDisplay + (p.IsNullableValueType ? "?" : string.Empty)));

        foreach (var isAsync in model.GenerateSync ? new[] { true, false } : new[] { true })
        {
          var name = type.Prefix + baseName + (isAsync ? "Async" : string.Empty);
          if (hiddenNames.Contains(name))
          {
            diagnostics.Add(Diagnostic(DataPortalOperationsDiagnostics.ExtensionNameHiddenId, method.Location, name, type.TypeName, $"{receiverInterface}<T>.{name}"));
            continue;
          }

          if (!signatures.Add($"{receiverInterface}.{name}({parameterTypes})"))
          {
            diagnostics.Add(Diagnostic(DataPortalOperationsDiagnostics.DuplicateExtensionMethodId, method.Location, name, type.TypeName, method.MethodDisplay));
            continue;
          }

          result.Add(new ExtensionMethod(method, name, isAsync, isChild));
        }
      }

      return result;
    }

    private static void AppendMethod(IndentedTextWriter writer, ExtensionTypeModel type, ExtensionMethod extension)
    {
      var method = extension.Method;
      var criteria = method.CriteriaParameters.ToList();
      var isDelete = method.Kind == "Delete";
      var criteriaNames = new HashSet<string>(criteria.Select(p => p.Name.TrimStart('@')), StringComparer.Ordinal);
      var receiver = GetUniqueName(ReceiverName, criteriaNames);
      var invoker = GetUniqueName(InvokerName, criteriaNames);
      var visibility = type.Visibility == TypeVisibility.Public && criteria.All(p => p.Visibility == TypeVisibility.Public)
        ? "public"
        : "internal";

      var returnType = (extension.IsAsync, isDelete) switch
      {
        (true, true) => "global::System.Threading.Tasks.Task",
        (true, false) => $"global::System.Threading.Tasks.Task<{type.FullyQualifiedName}>",
        (false, true) => "void",
        (false, false) => type.FullyQualifiedName
      };

      var portalType = extension.IsChild
        ? $"global::Csla.IChildDataPortal<{type.FullyQualifiedName}>"
        : $"global::Csla.IDataPortal<{type.FullyQualifiedName}>";
      var invokerType = extension.IsChild
        ? $"global::Csla.IChildDataPortalOperationInvoker<{type.FullyQualifiedName}>"
        : $"global::Csla.IDataPortalOperationInvoker<{type.FullyQualifiedName}>";

      var parameters = new List<string> { $"this {portalType} {receiver}" };
      foreach (var parameter in criteria)
      {
        var declaration = $"{(parameter.IsParams ? "params " : string.Empty)}{parameter.TypeDisplay} {parameter.Name}";
        if (parameter.DefaultValueExpression is not null)
          declaration += $" = {parameter.DefaultValueExpression}";
        parameters.Add(declaration);
      }

      var criteriaArray = criteria.Count == 0
        ? "global::System.Array.Empty<object?>()"
        : $"new object?[] {{ {string.Join(", ", criteria.Select(p => p.Name))} }}";

      var portalMethod = method.Kind + (extension.IsAsync ? "Async" : string.Empty);
      var invokerMethod = method.Kind + "ByOperation" + (extension.IsAsync ? "Async" : string.Empty);
      var invokerArguments = extension.IsChild
        ? $"\"{method.OperationName}\", {criteriaArray}"
        : $"\"{method.OperationName}\", {(method.RunLocal ? "true" : "false")}, {criteriaArray}";
      var fallbackArguments = criteria.Count == 0 ? string.Empty : criteriaArray;
      var returnKeyword = isDelete && !extension.IsAsync ? string.Empty : "return ";

      writer.WriteLine("/// <summary>");
      writer.WriteLine($"/// Invokes the <c>{Escape(method.MethodDisplay)}</c> {method.Kind} operation of <see cref=\"{type.FullyQualifiedName}\"/>.");
      writer.WriteLine("/// </summary>");
      writer.WriteLine($"{visibility} static {returnType} {OperationDiscovery.EscapeIdentifier(extension.Name)}({string.Join(", ", parameters)})");
      OpenBlock(writer);
      writer.WriteLine($"if ({receiver} is {invokerType} {invoker})");
      writer.Indent++;
      if (isDelete && !extension.IsAsync)
      {
        writer.WriteLine($"{invoker}.{invokerMethod}({invokerArguments});");
        writer.Indent--;
        writer.WriteLine("else");
        writer.Indent++;
        writer.WriteLine($"{receiver}.{portalMethod}({fallbackArguments});");
        writer.Indent--;
      }
      else
      {
        writer.WriteLine($"{returnKeyword}{invoker}.{invokerMethod}({invokerArguments});");
        writer.Indent--;
        writer.WriteLine($"{returnKeyword}{receiver}.{portalMethod}({fallbackArguments});");
      }
      CloseBlock(writer);
    }

    /// <summary>
    /// Returns a name for a generated parameter or local that does not
    /// collide with any operation parameter name.
    /// </summary>
    private static string GetUniqueName(string name, HashSet<string> usedNames)
    {
      while (usedNames.Contains(name))
        name = "__" + name;
      return name;
    }

    private static string Escape(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    private static DiagnosticInfo Diagnostic(string id, LocationInfo? location, params string[] args)
      => new(id, location, new EquatableArray<string>(args));

    private static void OpenBlock(IndentedTextWriter writer)
    {
      writer.WriteLine("{");
      writer.Indent++;
    }

    private static void CloseBlock(IndentedTextWriter writer)
    {
      writer.Indent--;
      writer.WriteLine("}");
    }

    /// <summary>
    /// A generated extension method for an operation method.
    /// </summary>
    internal sealed record ExtensionMethod(OperationMethodModel Method, string Name, bool IsAsync, bool IsChild);
  }
}
