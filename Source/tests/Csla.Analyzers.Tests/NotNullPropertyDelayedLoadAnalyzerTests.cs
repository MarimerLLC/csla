using Microsoft.CodeAnalysis;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace Csla.Analyzers.Tests
{
  [TestClass]
  public sealed class NotNullPropertyDelayedLoadAnalyzerTests
  {
    [TestMethod]
    public void VerifySupportedDiagnostics()
    {
      var diagnostics = new NotNullPropertyDelayedLoadAnalyzer().SupportedDiagnostics;
      Assert.AreEqual(1, diagnostics.Length);
      var diagnostic = diagnostics[0];
      Assert.AreEqual("CSLA0036", diagnostic.Id);
      Assert.AreEqual(Constants.AnalyzerIdentifiers.NotNullPropertyDelayedLoad, diagnostic.Id);
      Assert.AreEqual("Not-null properties don't support delayed loading", diagnostic.Title.ToString());
      Assert.AreEqual(Constants.Categories.Usage, diagnostic.Category);
      Assert.AreEqual(DiagnosticSeverity.Error, diagnostic.DefaultSeverity);
      Assert.AreEqual(HelpUrlBuilder.Build(Constants.AnalyzerIdentifiers.NotNullPropertyDelayedLoad, nameof(NotNullPropertyDelayedLoadAnalyzer)),
        diagnostic.HelpLinkUri);
    }

    private static string BusinessObjectWith(string baseType, string fieldType, string member) =>
      $$"""
      #nullable enable
      using System;
      using System.Threading.Tasks;
      using Csla;

      public class Child : BusinessBase<Child> { }

      public partial class A : {{baseType}}<A>
      {
        public static readonly {{fieldType}} ItemProperty = {{(fieldType.StartsWith("NotNull") ? "RegisterNotNullProperty" : "RegisterProperty")}}<{{fieldType.Substring(fieldType.IndexOf('<') + 1).TrimEnd('>')}}>(nameof(Item));
        {{member}}
      }
      """;

    [DataTestMethod]
    [DataRow("BusinessBase", "public Child Item => LazyGetProperty(ItemProperty, () => new Child())!;", "LazyGetProperty")]
    [DataRow("BusinessBase", "public Child Item => LazyGetPropertyAsync(ItemProperty, Task.FromResult(new Child()))!;", "LazyGetPropertyAsync")]
    [DataRow("BusinessBase", "public Child Item => LazyReadProperty(ItemProperty, () => new Child())!;", "LazyReadProperty")]
    [DataRow("BusinessBase", "public Child Item => LazyReadPropertyAsync(ItemProperty, () => Task.FromResult(new Child()))!;", "LazyReadPropertyAsync")]
    [DataRow("BusinessBase", "public Child Item => GetProperty(ItemProperty); public void Load() => LoadPropertyAsync(ItemProperty, Task.FromResult(new Child()));", "LoadPropertyAsync")]
    [DataRow("ReadOnlyBase", "public Child Item => LazyGetProperty(ItemProperty, () => new Child())!;", "LazyGetProperty")]
    [DataRow("ReadOnlyBase", "public Child Item => GetProperty(ItemProperty); public void Load() => LoadPropertyAsync(ItemProperty, Task.FromResult(new Child()));", "LoadPropertyAsync")]
    public async Task ReportsEachDelayedLoadMethod(string baseType, string member, string method)
    {
      var code = BusinessObjectWith(baseType, "NotNullPropertyInfo<Child>", member);
      var diagnostics = await TestHelpers.GetDiagnosticsOfValidCodeAsync<NotNullPropertyDelayedLoadAnalyzer>(code);
      Assert.AreEqual(1, diagnostics.Count, string.Join(Environment.NewLine, diagnostics));
      var location = diagnostics[0].Location;
      Assert.AreEqual("ItemProperty", location.SourceTree.ToString().Substring(location.SourceSpan.Start, location.SourceSpan.Length));
      StringAssert.Contains(diagnostics[0].GetMessage(), "'Item'");
      StringAssert.Contains(diagnostics[0].GetMessage(), method);
    }

    [TestMethod]
    public async Task ReportsValueType()
    {
      var code = BusinessObjectWith("BusinessBase", "NotNullPropertyInfo<int>",
        "public int Item => LazyGetProperty(ItemProperty, () => 42);");
      var diagnostics = await TestHelpers.GetDiagnosticsOfValidCodeAsync<NotNullPropertyDelayedLoadAnalyzer>(code);
      Assert.AreEqual(1, diagnostics.Count, string.Join(Environment.NewLine, diagnostics));
    }

    [TestMethod]
    public async Task ReportsGeneratedField()
    {
      var code =
        """
        #nullable enable
        using Csla;

        public class Child : BusinessBase<Child> { }

        public partial class A : BusinessBase<A>
        {
          public Child Item => LazyGetProperty(ItemProperty, () => new Child())!;
        }
        """;
      var generated =
        """
        // <auto-generated/>
        #nullable enable
        using Csla;
        partial class A
        {
          public static readonly NotNullPropertyInfo<Child> ItemProperty = RegisterNotNullProperty<Child>(nameof(Item));
        }
        """;
      var diagnostics = await TestHelpers.GetDiagnosticsOfValidCodeAsync<NotNullPropertyDelayedLoadAnalyzer>(code, generated);
      Assert.AreEqual(1, diagnostics.Count, string.Join(Environment.NewLine, diagnostics));
    }

    [TestMethod]
    public async Task SilentForPropertyInfo()
    {
      var code = BusinessObjectWith("BusinessBase", "PropertyInfo<Child>",
        "public Child Item => LazyGetProperty(ItemProperty, () => new Child())!;");
      var diagnostics = await TestHelpers.GetDiagnosticsOfValidCodeAsync<NotNullPropertyDelayedLoadAnalyzer>(code);
      Assert.AreEqual(0, diagnostics.Count, string.Join(Environment.NewLine, diagnostics));
    }

    [TestMethod]
    public async Task SilentForOtherMethods()
    {
      var code = BusinessObjectWith("BusinessBase", "NotNullPropertyInfo<Child>",
        "public Child Item => GetProperty(ItemProperty); public void Load(Child value) => LoadProperty(ItemProperty, value);");
      var diagnostics = await TestHelpers.GetDiagnosticsOfValidCodeAsync<NotNullPropertyDelayedLoadAnalyzer>(code);
      Assert.AreEqual(0, diagnostics.Count, string.Join(Environment.NewLine, diagnostics));
    }
  }
}
