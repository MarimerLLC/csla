using Microsoft.CodeAnalysis;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace Csla.Analyzers.Tests
{
  [TestClass]
  public sealed class NotNullPropertyNotSerializedAnalyzerTests
  {
    [TestMethod]
    public void VerifySupportedDiagnostics()
    {
      var diagnostics = new NotNullPropertyNotSerializedAnalyzer().SupportedDiagnostics;
      Assert.AreEqual(1, diagnostics.Length);
      var diagnostic = diagnostics[0];
      Assert.AreEqual(Constants.AnalyzerIdentifiers.NotNullPropertyNotSerializedWithoutDefault, diagnostic.Id);
      Assert.AreEqual("CSLA0032", diagnostic.Id);
      Assert.AreEqual("Not-serialized not-null properties need a default value", diagnostic.Title.ToString());
      Assert.AreEqual(Constants.Categories.Usage, diagnostic.Category);
      Assert.AreEqual(DiagnosticSeverity.Error, diagnostic.DefaultSeverity);
      Assert.AreEqual(HelpUrlBuilder.Build(Constants.AnalyzerIdentifiers.NotNullPropertyNotSerializedWithoutDefault, nameof(NotNullPropertyNotSerializedAnalyzer)),
        diagnostic.HelpLinkUri);
    }

    private static string BusinessObjectWith(string members) =>
      $$"""
      #nullable enable
      using Csla;

      public class Child : BusinessBase<Child> { }

      public partial class A : BusinessBase<A>
      {
        {{members}}
      }
      """;

    private static async Task AssertReportedAsync(string code, string locationText, params string[] additionalSources)
    {
      var diagnostics = await TestHelpers.GetDiagnosticsAsync<NotNullPropertyNotSerializedAnalyzer>(code, additionalSources);
      Assert.AreEqual(1, diagnostics.Count, string.Join(Environment.NewLine, diagnostics));
      Assert.AreEqual(Constants.AnalyzerIdentifiers.NotNullPropertyNotSerializedWithoutDefault, diagnostics[0].Id);
      Assert.AreEqual(locationText, diagnostics[0].Location.SourceTree.ToString().Substring(
        diagnostics[0].Location.SourceSpan.Start, diagnostics[0].Location.SourceSpan.Length));
    }

    private static async Task AssertSilentAsync(string code, params string[] additionalSources)
    {
      var diagnostics = await TestHelpers.GetDiagnosticsAsync<NotNullPropertyNotSerializedAnalyzer>(code, additionalSources);
      Assert.AreEqual(0, diagnostics.Count, string.Join(Environment.NewLine, diagnostics));
    }

    [TestMethod]
    public async Task ReportsDoNotSerializeWithoutDefault()
    {
      var code = BusinessObjectWith(
        """
        public static readonly NotNullPropertyInfo<Child> ChildProperty = RegisterNotNullProperty<Child>(nameof(Item));
        [DoNotSerialize]
        public Child Item { get => GetProperty(ChildProperty); set => SetProperty(ChildProperty, value); }
        """);
      await AssertReportedAsync(code, "Item");
    }

    [TestMethod]
    public async Task ReportsCalculatedPropertyWithoutDefault()
    {
      var code = BusinessObjectWith(
        """
        public static readonly NotNullPropertyInfo<Child> ItemProperty = RegisterNotNullProperty<Child>(nameof(Item));
        [CalculatedProperty]
        public Child Item => GetProperty(ItemProperty);
        """);
      await AssertReportedAsync(code, "Item");
    }

    [TestMethod]
    public async Task ReportsNonPublicProperty()
    {
      var code = BusinessObjectWith(
        """
        private static readonly NotNullPropertyInfo<Child> ItemProperty = RegisterNotNullProperty<Child>(nameof(Item));
        [DoNotSerialize]
        private Child Item => GetProperty(ItemProperty);
        """);
      await AssertReportedAsync(code, "Item");
    }

    [TestMethod]
    public async Task ReportsStringWithoutDefault()
    {
      var code = BusinessObjectWith(
        """
        public static readonly NotNullPropertyInfo<string> NameProperty = RegisterNotNullProperty<string>(nameof(Name));
        [DoNotSerialize]
        public string Name => GetProperty(NameProperty);
        """);
      await AssertReportedAsync(code, "Name");
    }

    [TestMethod]
    public async Task ReportsGeneratedRegistration()
    {
      var code = BusinessObjectWith(
        """
        [DoNotSerialize]
        public Child Item => GetProperty(ItemProperty);
        """);
      var generated =
        """
        // <auto-generated/>
        #nullable enable
        using Csla;
        partial class A
        {
          public static readonly NotNullPropertyInfo<Child> ItemProperty = RegisterNotNullProperty<Child>(nameof(Item));
        }
        """;
      await AssertReportedAsync(code, "Item", generated);
    }

    [TestMethod]
    public async Task SilentForGeneratedStringRegistration()
    {
      var code = BusinessObjectWith(
        """
        [DoNotSerialize]
        public string Name => GetProperty(NameProperty);
        """);
      var generated =
        """
        // <auto-generated/>
        #nullable enable
        using Csla;
        partial class A
        {
          public static readonly NotNullPropertyInfo<string> NameProperty = RegisterNotNullProperty<string>(nameof(Name), null, string.Empty);
        }
        """;
      await AssertSilentAsync(code, generated);
    }

    [TestMethod]
    public async Task SilentWithDefault()
    {
      var code = BusinessObjectWith(
        """
        public static readonly NotNullPropertyInfo<Child> ItemProperty = RegisterNotNullProperty<Child>(nameof(Item), null, new Child());
        [DoNotSerialize]
        public Child Item => GetProperty(ItemProperty);
        """);
      await AssertSilentAsync(code);
    }

    [TestMethod]
    public async Task SilentForValueType()
    {
      var code = BusinessObjectWith(
        """
        public static readonly NotNullPropertyInfo<int> CountProperty = RegisterNotNullProperty<int>(nameof(Count));
        [DoNotSerialize]
        public int Count => GetProperty(CountProperty);
        """);
      await AssertSilentAsync(code);
    }

    [TestMethod]
    public async Task SilentForAttributeOnFieldOnly()
    {
      var code = BusinessObjectWith(
        """
        [DoNotSerialize]
        public static readonly NotNullPropertyInfo<Child> ItemProperty = RegisterNotNullProperty<Child>(nameof(Item));
        public Child Item => GetProperty(ItemProperty);
        """);
      await AssertSilentAsync(code);
    }

    [TestMethod]
    public async Task SilentForPropertyInfo()
    {
      var code = BusinessObjectWith(
        """
        public static readonly PropertyInfo<Child> ItemProperty = RegisterProperty<Child>(nameof(Item));
        [DoNotSerialize]
        public Child Item => GetProperty(ItemProperty)!;
        """);
      await AssertSilentAsync(code);
    }

    [TestMethod]
    public async Task SilentForRegistrationOfAnotherName()
    {
      var code = BusinessObjectWith(
        """
        public static readonly NotNullPropertyInfo<Child> OtherProperty = RegisterNotNullProperty<Child>(nameof(Other));
        public Child Other => GetProperty(OtherProperty);
        [DoNotSerialize]
        public Child Item => GetProperty(OtherProperty);
        """);
      await AssertSilentAsync(code);
    }

    [TestMethod]
    public async Task SilentForUnknownRegistration()
    {
      var code = BusinessObjectWith(
        """
        public static readonly NotNullPropertyInfo<Child> ItemProperty = Make();
        private static NotNullPropertyInfo<Child> Make() => RegisterNotNullProperty<Child>(nameof(Item));
        [DoNotSerialize]
        public Child Item => GetProperty(ItemProperty);
        """);
      await AssertSilentAsync(code);
    }
  }
}
