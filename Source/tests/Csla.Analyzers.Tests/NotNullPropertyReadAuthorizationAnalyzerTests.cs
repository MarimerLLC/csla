using Microsoft.CodeAnalysis;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace Csla.Analyzers.Tests
{
  [TestClass]
  public sealed class NotNullPropertyReadAuthorizationAnalyzerTests
  {
    [TestMethod]
    public void VerifySupportedDiagnostics()
    {
      var diagnostics = new NotNullPropertyReadAuthorizationAnalyzer().SupportedDiagnostics;
      Assert.AreEqual(1, diagnostics.Length);
      var diagnostic = diagnostics[0];
      Assert.AreEqual("CSLA0034", diagnostic.Id);
      Assert.AreEqual(Constants.AnalyzerIdentifiers.NotNullPropertyWithReadAuthorization, diagnostic.Id);
      Assert.AreEqual("Not-null properties with read authorization rules need a default value", diagnostic.Title.ToString());
      Assert.AreEqual(Constants.Categories.Usage, diagnostic.Category);
      Assert.AreEqual(DiagnosticSeverity.Warning, diagnostic.DefaultSeverity);
      Assert.AreEqual(HelpUrlBuilder.Build(Constants.AnalyzerIdentifiers.NotNullPropertyWithReadAuthorization, nameof(NotNullPropertyReadAuthorizationAnalyzer)),
        diagnostic.HelpLinkUri);
    }

    private static string BusinessObjectWith(string registration, string rule) =>
      $$"""
      #nullable enable
      using Csla;
      using Csla.Rules;
      using Csla.Rules.CommonRules;

      public class Child : BusinessBase<Child> { }

      public partial class A : BusinessBase<A>
      {
        public static readonly NotNullPropertyInfo<Child> ItemProperty = {{registration}};
        public Child Item => GetProperty(ItemProperty);

        protected override void AddBusinessRules()
        {
          base.AddBusinessRules();
          {{rule}}
        }
      }
      """;

    private static async Task<List<Diagnostic>> GetDiagnosticsAsync(string code, params string[] additionalSources) =>
      await TestHelpers.GetDiagnosticsOfValidCodeAsync<NotNullPropertyReadAuthorizationAnalyzer>(code, additionalSources);

    [TestMethod]
    public async Task ReportsReadRuleWithoutDefault()
    {
      var code = BusinessObjectWith("RegisterNotNullProperty<Child>(nameof(Item))",
        "BusinessRules.AddRule(new IsInRole(AuthorizationActions.ReadProperty, ItemProperty, \"Admin\"));");
      var diagnostics = await GetDiagnosticsAsync(code);
      Assert.AreEqual(1, diagnostics.Count, string.Join(Environment.NewLine, diagnostics));
      var location = diagnostics[0].Location;
      Assert.AreEqual("new IsInRole(AuthorizationActions.ReadProperty, ItemProperty, \"Admin\")",
        location.SourceTree.ToString().Substring(location.SourceSpan.Start, location.SourceSpan.Length));
      StringAssert.Contains(diagnostics[0].GetMessage(), "'Item'");
    }

    [TestMethod]
    public async Task ReportsStringWithoutDefault()
    {
      var code =
        """
